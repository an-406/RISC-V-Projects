`timescale 1ns/1ps

module tb_immgen;

logic [31:0] inst_i;
logic [31:0] imm_o;

//=====================================
// DUT
//=====================================
immgen dut(
    .inst_i(inst_i),
    .imm_o(imm_o)
);

//=====================================
// Check Task
//=====================================
task automatic check;
    input [31:0] inst;
    input [31:0] expected;
begin
    inst_i = inst;
    #1;

    if(imm_o === expected)
        $display("PASS  inst=%h  imm=%h", inst, imm_o);
    else
        $display("FAIL  inst=%h  expected=%h  got=%h",
                  inst, expected, imm_o);
end
endtask

//=====================================
// Test
//=====================================
initial begin

//-------------------------------------------------
// I-Type
// addi x1,x2,10
//-------------------------------------------------
check(
32'h00A10093,
32'd10
);

//-------------------------------------------------
// I-Type Negative
// imm = -1
//-------------------------------------------------
check(
32'hFFF10093,
32'hFFFFFFFF
);

//-------------------------------------------------
// S-Type
// sw x5,20(x2)
//-------------------------------------------------
check(
32'h00512A23,
32'd20
);

//-------------------------------------------------
// S-Type Negative
//-------------------------------------------------
check(
32'hFE512823,
32'hFFFFFFF0
);

//-------------------------------------------------
// B-Type
// offset = 16
//-------------------------------------------------
check(
32'h00208863,
32'd16
);

//-------------------------------------------------
// B-Type Negative
//-------------------------------------------------
check(
32'hFE2088E3,
32'hFFFFFFF0
);

//-------------------------------------------------
// U-Type
// lui x1,0x12345
//-------------------------------------------------
check(
32'h123450B7,
32'h12345000
);

//-------------------------------------------------
// AUIPC
//-------------------------------------------------
check(
32'hABCDE117,
32'hABCDE000
);

//-------------------------------------------------
// J-Type
// jal offset = 8
//-------------------------------------------------
check(
32'h008000EF,
32'd8
);

//-------------------------------------------------
// J-Type Negative
//-------------------------------------------------
check(
32'hFF9FF0EF,
32'hFFFFFFF8
);

//-------------------------------------------------
// Unknown Opcode
//-------------------------------------------------
check(
32'hFFFFFFFF,
32'h00000000
);

$display("--------------------------------");
$display("IMMGEN TEST FINISHED");
$display("--------------------------------");

#10;
$finish;

end

endmodule
