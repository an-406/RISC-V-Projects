`timescale 1ns/1ps

module tb_alu;

logic [31:0] rs1_i;
logic [31:0] rs2_i;
logic [3:0]  alu_control_i;
logic [31:0] rd_o;

//=========================================
// DUT
//=========================================
alu dut(
    .rs1_i(rs1_i),
    .rs2_i(rs2_i),
    .alu_control_i(alu_control_i),
    .rd_o(rd_o)
);

//=========================================
// CHECK TASK
//=========================================
task automatic check;
    input [31:0] rs1;
    input [31:0] rs2;
    input [3:0] control;
    input [31:0] expected;

begin
    rs1_i = rs1;
    rs2_i = rs2;
    alu_control_i = control;
    #10;

    if(rd_o === expected)
        $display("PASS ctrl=%b rs1=%h rs2=%h result=%h",
                  control,rs1,rs2,rd_o);
    else
        $display("FAIL ctrl=%b rs1=%h rs2=%h result=%h expected=%h",
                  control,rs1,rs2,rd_o,expected);
end
endtask

//=========================================
// TEST
//=========================================
initial begin

//----------------------------------
// AND
//----------------------------------
check(32'hAA55AA55,32'hFFFF0000,4'b0000,32'hAA550000);

//----------------------------------
// OR
//----------------------------------
check(32'hAA550000,32'h0000FFFF,4'b0001,32'hAA55FFFF);

//----------------------------------
// XOR
//----------------------------------
check(32'hFFFF0000,32'h00FFFF00,4'b0011,32'hFF00FF00);

//----------------------------------
// ADD
//----------------------------------
check(10,20,4'b0010,30);
check(32'hFFFFFFFF,1,4'b0010,0);

//----------------------------------
// SUB
//----------------------------------
check(20,10,4'b0110,10);
check(10,20,4'b0110,32'hFFFFFFF6);

//----------------------------------
// SLT (signed)
//----------------------------------
check(-5,3,4'b0111,1);
check(5,3,4'b0111,0);
check(-1,-2,4'b0111,0);

//----------------------------------
// SLTU (unsigned)
//----------------------------------
check(5,10,4'b0100,1);
check(10,5,4'b0100,0);
check(32'hFFFFFFFF,1,4'b0100,0);

//----------------------------------
// SLL
//----------------------------------
check(32'h00000001,4,4'b1001,32'h00000010);

//----------------------------------
// SRL
//----------------------------------
check(32'h80000000,1,4'b1000,32'h40000000);

//----------------------------------
// SRA
//----------------------------------
check(32'h80000000,1,4'b1010,32'hC0000000);
check(32'hFFFFFFF0,2,4'b1010,32'hFFFFFFFC);

// Overflow
check(32'h7FFFFFFF,1,4'b0010,32'h80000000);

// Signed compare
check(32'h80000000,0,4'b0111,1);

// Unsigned compare
check(32'h80000000,0,4'b0100,0);

// Shift 31 bit
check(32'h1,31,4'b1001,32'h80000000);
check(32'h80000000,31,4'b1000,32'h00000001);
check(32'h80000000,31,4'b1010,32'hFFFFFFFF);

//----------------------------------
$display("--------------------------");
$display("Simulation Finished");
$display("--------------------------");

$finish;

end

endmodule
